/**
 * `wp-build sync-agent-files` — copies the shared agent files for the
 * project's kind (`agent/plugin` or `agent/theme` in this package) into the
 * repo: `.claude/instructions/` (conventions, commit format) and
 * `.claude/skills/`, plus any root files such as `skills-lock.json`.
 *
 * The copies are generated: edit them in wp-shared, then sync. A manifest,
 * `.claude/wp-shared.json`, lists what was written, so a file later removed
 * from wp-shared is removed here too — and nothing else is ever touched.
 *
 * The repo's own `CLAUDE.md` stays its own; sync only makes sure it imports
 * the shared conventions (`@.claude/instructions/CONVENTIONS.md`).
 */

import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'fs';
import { dirname, relative, resolve } from 'path';
import { loadProject }                from './project';

const MANIFEST = '.claude/wp-shared.json';
const IMPORT   = '@.claude/instructions/CONVENTIONS.md';

interface Manifest {
  readonly note: string;
  readonly version: string;
  readonly files: string[];
}

export function syncAgentFilesCommand(): void {
  const project = loadProject();
  const source  = resolve( __dirname, '..', 'agent', project.kind );
  const version = ( JSON.parse( readFileSync( resolve( __dirname, '..', 'package.json' ), 'utf8' ) ) as { version: string } ).version;

  const files = walk( source ).map( ( abs ) => relative( source, abs ).replace( /\\/g, '/' ) ).sort();

  // Files written by an earlier sync that wp-shared no longer has.
  const manifestPath = resolve( project.dir, MANIFEST );
  const previous     = existsSync( manifestPath ) ? ( JSON.parse( readFileSync( manifestPath, 'utf8' ) ) as Manifest ).files : [];
  for ( const stale of previous.filter( ( f ) => ! files.includes( f ) ) ) {
    rmSync( resolve( project.dir, stale ), { force: true } );
    console.log( `sync-agent-files: removed ${ stale }` );
  }

  for ( const rel of files ) {
    const to = resolve( project.dir, rel );
    mkdirSync( dirname( to ), { recursive: true } );
    copyFileSync( resolve( source, rel ), to );
  }

  const manifest: Manifest = {
    note: 'Generated by `wp-build sync-agent-files` from Pentadeep-Co/wp-shared. Edit the files there, not here.',
    version,
    files,
  };
  mkdirSync( dirname( manifestPath ), { recursive: true } );
  writeFileSync( manifestPath, JSON.stringify( manifest, null, 2 ) + '\n' );
  console.log( `sync-agent-files: ${ files.length } ${ project.kind } files from wp-shared ${ version }` );

  ensureImport( resolve( project.dir, 'CLAUDE.md' ) );
}

/** Adds the conventions import to CLAUDE.md, after its title, if it lacks one. */
function ensureImport( file: string ): void {
  if ( ! existsSync( file ) ) {
    console.warn( 'sync-agent-files: no CLAUDE.md here — write one; it should import the shared conventions with ' + IMPORT );
    return;
  }
  const text = readFileSync( file, 'utf8' );
  if ( text.includes( IMPORT ) ) {
    return;
  }
  const line  = `Shared conventions for every Pentadeep repo of this kind (synced from wp-shared):\n${ IMPORT }\n`;
  const lines = text.split( /\r?\n/ );
  const title = lines.findIndex( ( l ) => l.startsWith( '# ' ) );
  lines.splice( title + 1, 0, '', line.trimEnd() );
  writeFileSync( file, lines.join( '\n' ) );
  console.log( `sync-agent-files: CLAUDE.md now imports ${ IMPORT }` );
}

function walk( dir: string ): string[] {
  return readdirSync( dir, { withFileTypes: true } ).flatMap( ( entry ) => {
    const path = resolve( dir, entry.name );
    return entry.isDirectory() ? walk( path ) : [ path ];
  } );
}
